`ifndef DEFINES_SV
`define DEFINES_SV

// ----------------------------------------------------------------------------
// RV32I 操作码编码 (inst[6:0])
// ----------------------------------------------------------------------------
`define OPCODE_LUI      7'b0110111  // 加载高位立即数 (U-type)
`define OPCODE_AUIPC    7'b0010111  // PC 加高位立即数 (U-type)
`define OPCODE_JAL      7'b1101111  // 跳转并链接 (J-type)
`define OPCODE_JALR     7'b1100111  // 寄存器跳转并链接 (I-type)
`define OPCODE_BRANCH   7'b1100011  // 分支指令 (B-type)
`define OPCODE_LOAD     7'b0000011  // 加载指令 (I-type)
`define OPCODE_STORE    7'b0100011  // 存储指令 (S-type)
`define OPCODE_ALU_IMM  7'b0010011  // ALU 立即数操作 (I-type)
`define OPCODE_ALU      7'b0110011  // ALU 寄存器操作 (R-type)
`define OPCODE_FENCE    7'b0001111  // 内存排序栅障 (I-type)

// ----------------------------------------------------------------------------
// 分支指令 Funct3 编码
// ----------------------------------------------------------------------------
`define FUNCT3_BEQ      3'b000
`define FUNCT3_BNE      3'b001
`define FUNCT3_BLT      3'b100
`define FUNCT3_BGE      3'b101
`define FUNCT3_BLTU     3'b110
`define FUNCT3_BGEU     3'b111

// ----------------------------------------------------------------------------
// 加载指令 Funct3 编码
// ----------------------------------------------------------------------------
`define FUNCT3_LB       3'b000
`define FUNCT3_LH       3'b001
`define FUNCT3_LW       3'b010
`define FUNCT3_LBU      3'b100
`define FUNCT3_LHU      3'b101

// ----------------------------------------------------------------------------
// 存储指令 Funct3 编码
// ----------------------------------------------------------------------------
`define FUNCT3_SB       3'b000
`define FUNCT3_SH       3'b001
`define FUNCT3_SW       3'b010

// ----------------------------------------------------------------------------
// ALU 立即数 / 寄存器指令 Funct3 编码
// ----------------------------------------------------------------------------
`define FUNCT3_ADD_SUB  3'b000
`define FUNCT3_SLL      3'b001
`define FUNCT3_SLT      3'b010
`define FUNCT3_SLTU     3'b011
`define FUNCT3_XOR      3'b100
`define FUNCT3_SRL_SRA  3'b101
`define FUNCT3_OR       3'b110
`define FUNCT3_AND      3'b111

// ----------------------------------------------------------------------------
// R-type 指令 Funct7 区分码
// ----------------------------------------------------------------------------
`define FUNCT7_NORMAL   7'b0000000  // 普通操作 (ADD, SLL 等)
`define FUNCT7_ALT      7'b0100000  // 备选操作 (SUB, SRA)

// ----------------------------------------------------------------------------
// ALU 操作码 (3 位)
// ----------------------------------------------------------------------------
`define ALU_OP_ADD      3'b000
`define ALU_OP_SUB      3'b001
`define ALU_OP_AND      3'b010
`define ALU_OP_OR       3'b011
`define ALU_OP_XOR      3'b100
`define ALU_OP_SLL      3'b101
`define ALU_OP_SRL      3'b110
`define ALU_OP_SRA      3'b111

// ----------------------------------------------------------------------------
// 访存宽度 (funct3 低 2 位)
// ----------------------------------------------------------------------------
`define MEM_WIDTH_BYTE   2'b00
`define MEM_WIDTH_HALF   2'b01
`define MEM_WIDTH_WORD   2'b10

// ----------------------------------------------------------------------------
// 分支预测器参数 (优化版)
// ----------------------------------------------------------------------------
// BTB: 128 项, 2 路组相联
//   - 64 组 × 2 路 = 128 项
//   - 索引: PC[7:2] (6 位, 对应 64 组)
//   - 标签: PC[13:8] (6 位)
`define BTB_ENTRIES      128        // BTB 总项数 (2 路 × 64 组)
`define BTB_WAYS         2          // 2 路组相联
`define BTB_SETS         64         // 组数
`define BTB_INDEX_BITS   6          // log2(64) = 6 位索引
`define BTB_TAG_BITS     6          // 6 位标签
`define BHT_COUNTER_BITS 2          // 2 位饱和计数器

// RAS (返回地址栈)
`define RAS_DEPTH        8          // 8 项 RAS, 用于函数返回

// ----------------------------------------------------------------------------
// 流水线控制信号
// ----------------------------------------------------------------------------
`define PC_RESET_VALUE   32'h0000_0000

`endif // DEFINES_SV
